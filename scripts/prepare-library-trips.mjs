import sharp from 'sharp'
import { mkdir, readdir, copyFile, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { TRIP_ASSET_MANIFEST } from './trip-asset-manifest.mjs'

const source = process.argv[2]
if (!source) throw new Error('Uso: node scripts/prepare-library-trips.mjs "ruta/Biblioteca de viajes/Viajes"')
const root = resolve(source)
await readdir(root) // Validate the source before producing any output.
await readdir(resolve('public/media/trips'))
await readdir(resolve('src/data'))
const result = {}
const sheetNames = ['portada', 'ruta', 'itinerario', 'esencia']
const titles = ['Portada', 'La ruta', 'El viaje', 'Lo que me llevo']
for (const entry of TRIP_ASSET_MANIFEST) {
  const directory = join(root, entry.folder)
  const files = await readdir(directory)
  const inputs = entry.sources.map(prefix => {
    if (!prefix) return null
    const matches = files.filter(file => file.startsWith(prefix) && /\.png$/i.test(file))
    if (matches.length !== 1) throw new Error(`${entry.id}: fuente ambigua o ausente: ${prefix}`)
    return join(directory, matches[0])
  })
  const output = resolve(`public/media/trips/${entry.id}`)
  await mkdir(`${output}/originals`, { recursive: true })
  const sheets = []
  for (const [index, input] of inputs.entries()) {
    if (!input) continue
    const { width, height } = await sharp(input).metadata()
    const name = sheetNames[index]
    await copyFile(input, `${output}/originals/${name}.png`)
    sheets.push({ title: titles[index], src: `/media/trips/${entry.id}/originals/${name}.png`, width, height })
  }
  async function crop(input, name, box, maxWidth) {
    const { width, height } = await sharp(input).metadata()
    const left = Math.round(box[0] * width / 300)
    const top = Math.round(box[1] * height / 534)
    const cropWidth = Math.min(width - left, Math.round(box[2] * width / 300))
    const cropHeight = Math.min(height - top, Math.round(box[3] * height / 534))
    if (Math.min(left, top) < 0 || Math.min(cropWidth, cropHeight) <= 0) throw new Error(`${entry.id}: recorte inválido ${name}`)
    const info = await sharp(input).extract({ left, top, width: cropWidth, height: cropHeight })
      .resize({ width: maxWidth, withoutEnlargement: true }).webp({ quality: 85 }).toFile(`${output}/${name}.webp`)
    return { src: `/media/trips/${entry.id}/${name}.webp`, width: info.width, height: info.height }
  }
  const stages = []
  for (const [index, box] of entry.stages.entries()) stages.push(await crop(inputs[2], `etapa-${index+1}`, box, 440))
  const cover = entry.coverFromStage === undefined
    ? await crop(inputs[0], 'portada', entry.coverBox, 941)
    : stages[entry.coverFromStage]
  const map = await crop(inputs[1] ?? inputs[2], 'ruta', entry.mapBox, 800)
  const closingImage = await crop(inputs[3], 'esencia', entry.closingBox, 941)
  result[entry.id] = { cover, map, closingImage, stages, sheets, routeSheetIndex: sheets.findIndex(sheet => sheet.src.endsWith(inputs[1] ? '/ruta.png' : '/itinerario.png')) }
  console.log(`${entry.id}: ${stages.length} fotografías, ${sheets.length} originales`)
}
await writeFile(resolve('src/data/trip-assets.ts'), `// Generated by scripts/prepare-library-trips.mjs. Crop definitions live in scripts/trip-asset-manifest.mjs.\nexport const TRIP_ASSETS = ${JSON.stringify(result, null, 2)} as const\n`)
